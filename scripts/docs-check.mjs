#!/usr/bin/env node
/*
 * File: docs-check.mjs
 * Modification: 2026-10-11 — 官方網站雙語 .sm 文件一致性與解析驗證。
 */
import {readFile,readdir,mkdir,writeFile} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {parseDocument,toMarkdownDetailed} from '../dist/index.js';

const locales=['zh-tw','en'];
/** Validate content identity, parse errors and maintain two-language parity. */
export async function checkWebsiteDocs(root,{exportDir=null}={}) {
  const namesByLocale = await Promise.all(locales.map(async locale => {
    const entries=await readdir(join(root,locale));
    return entries.filter(x=>x.endsWith('.sm')).sort();
  }));
  const all=new Set(namesByLocale.flat());
  const errors=[];const warnings=[];
  let files=0;
  for (const name of [...all].sort()) {
    for (let i=0;i<locales.length;i++) {
      const locale=locales[i];
      if (!namesByLocale[i].includes(name)) {errors.push(`Missing ${locale}/${name}`);continue;}
      const source=await readFile(join(root,locale,name),'utf8');
      const document=parseDocument(source);
      files++;
      for(const d of document.diagnostics) {
        const msg=`${locale}/${name}:${d.position.line}:${d.position.column} ${d.code}: ${d.message}`;
        (d.severity==='error'?errors:warnings).push(msg);
      }
      if (exportDir) {
        const markdown=toMarkdownDetailed(document);
        for(const d of markdown.diagnostics) warnings.push(`${locale}/${name}:${d.position.line} ${d.code}: ${d.message}`);
        await mkdir(join(exportDir,locale),{recursive:true});
        await writeFile(join(exportDir,locale,name.replace(/\.sm$/,'.md')),`<!-- Generated from ${locale}/${name}. Do not edit this file. -->\n\n${markdown.source}`,'utf8');
      }
    }
  }
  return {files,errors,warnings};
}
if(process.argv[1] && fileURLToPath(import.meta.url)===resolve(process.argv[1])) {
  const root=resolve('apps/site/content');
  const exportDir=process.argv.includes('--export')?resolve('docs/generated-site'):null;
  try {
    const report=await checkWebsiteDocs(root,{exportDir});
    process.stdout.write(`Checked ${report.files} .sm documentation files, ${report.errors.length} errors, ${report.warnings.length} warnings.\n`);
    for(const issue of report.errors) process.stderr.write(`${issue}\n`);
    if(report.warnings.length) process.stdout.write(`Warnings (first 8):\n${report.warnings.slice(0,8).join('\n')}\n`);
    if(report.errors.length) process.exitCode=1;
  }catch(error){process.stderr.write(`Doc validation failed: ${error.message}\n`);process.exitCode=1;}
}
